def to_msys_path(path: Path) -> str:
    s = str(path.resolve()).replace("\\", "/")
    if len(s) >= 2 and s[1] == ":":
        return f"/{s[0].lower()}{s[2:]}"
    return s


def c_escape_utf8(text: str) -> str:
    out = []
    for b in text.encode("utf-8"):
        if b == 0x22:
            out.append('\\"')
        elif b == 0x5C:
            out.append("\\\\")
        elif 0x20 <= b <= 0x7E:
            out.append(chr(b))
        else:
            out.append(f'\\x{b:02x}""')
    return "".join(out)


def rc_escape_ascii(text: str) -> str:
    # RC VERSIONINFO strings work reliably with standard ASCII/Latin-1 escapes
    return text.replace("\\", "\\\\").replace('"', '""')


def run_msys(cmd: str, cwd: Path, check: bool = True, capture: bool = False) -> subprocess.CompletedProcess:
    if not MSYS2_BASH.exists():
        raise RuntimeError(f"MSYS2 bash not found at {MSYS2_BASH}")
    msys_cwd = to_msys_path(cwd)
    full_cmd = f"export PATH=/ucrt64/bin:/usr/bin:$PATH && cd '{msys_cwd}' && {cmd}"
    print(f"[MSYS2] {cmd}")
    env = os.environ.copy()
    env["MSYSTEM"] = "UCRT64"
    env["CHERE_INVOKING"] = "1"
    return subprocess.run(
        [str(MSYS2_BASH), "-lc", full_cmd],
        check=check,
        text=True,
        capture_output=capture,
        env=env,
    )


def generate_standalone_config_header(profile: dict, build_dir: Path) -> Path:
    header_path = build_dir / "base" / "standalone_config.h"
    header_path.parent.mkdir(parents=True, exist_ok=True)
    content = f"""/* Auto-generated by tools/standalone/build_standalone.py - DO NOT EDIT */
#ifndef BASE_STANDALONE_CONFIG_H
#define BASE_STANDALONE_CONFIG_H

#define STANDALONE_APP_ID "{c_escape_utf8(profile['app_id'])}"
#define STANDALONE_DISPLAY_NAME "{c_escape_utf8(profile['display_name'])}"
#define STANDALONE_ENGINE_ID "{c_escape_utf8(profile['engine'])}"
#define STANDALONE_GAME_ID "{c_escape_utf8(profile['game_id'])}"
#define STANDALONE_EXPECTED_LANGUAGE "{c_escape_utf8(profile.get('expected_language', ''))}"
#define STANDALONE_EXPECTED_PLATFORM "{c_escape_utf8(profile.get('expected_platform', ''))}"
#define STANDALONE_EXPECTED_EXTRA "{c_escape_utf8(profile.get('expected_extra', ''))}"
#define STANDALONE_TARGET_NAME "{c_escape_utf8(profile['target_name'])}"
#define STANDALONE_RUNTIME_ICON_FILE "{c_escape_utf8(profile.get('runtime_icon_file', ''))}"

#endif // BASE_STANDALONE_CONFIG_H
"""
    if not header_path.exists() or header_path.read_text(encoding="utf-8") != content:
        header_path.write_text(content, encoding="utf-8")
    return header_path


