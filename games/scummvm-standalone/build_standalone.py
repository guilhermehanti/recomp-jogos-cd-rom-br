def query_static_libs(build_dir: Path, config_mk_text: str) -> str:
    pkgs = ["sdl2", "libpng", "zlib", "freetype2", "fribidi"]
    if re.search(r"^USE_LIBCURL\s*=\s*1", config_mk_text, re.MULTILINE):
        pkgs.append("libcurl")
    if re.search(r"^USE_JPEG\s*=\s*1", config_mk_text, re.MULTILINE):
        pkgs.append("libjpeg")
    if re.search(r"^USE_VORBIS\s*=\s*1", config_mk_text, re.MULTILINE):
        pkgs.append("vorbisfile")

    res = run_msys(
        f"pkg-config --static --libs {' '.join(pkgs)}",
        cwd=build_dir,
        capture=True,
    )
    static_libs = res.stdout.strip()
    # Ensure standard Windows system libs required by ScummVM Win32 backend & static SDL3/curl
    extra_win_libs = (
        "-lmingw32 -lSDL2main -lSDL2 "
        "-lwinmm -lgdi32 -luser32 -lkernel32 -lshell32 -lole32 -loleaut32 -luuid "
        "-lwinspool -lcomdlg32 -lshlwapi -ladvapi32 -lversion -limm32 -lsetupapi "
        "-lcfgmgr32 -ldinput8 -lws2_32 -lcrypt32 -lbcrypt -lsecur32 -lwldap32 "
        "-liphlpapi -lrpcrt4 -lusp10 -ldwrite -lstdc++ -lwinpthread -lm"
    )
    return f"{static_libs} {extra_win_libs}"


def patch_config_mk_for_static_standalone(build_dir: Path) -> None:
    config_mk = build_dir / "config.mk"
    text = config_mk.read_text(encoding="utf-8")

    static_libs = query_static_libs(build_dir, text)

    # Replace LIBS += ... with full static library graph
    text = re.sub(r"^LIBS\s*\+=.*$", f"LIBS += {static_libs}", text, flags=re.MULTILINE)

    # Replace OBJS += dists/scummvm.o with dists/standalone.o
    text = re.sub(r"^OBJS\s*\+=\s*dists/scummvm\.o\s*$", "OBJS += dists/standalone.o", text, flags=re.MULTILINE)

    # Ensure -static and -mwindows in LDFLAGS for zero MSYS2 DLL dependencies and no console window
    static_ldflags = "-static -static-libgcc -static-libstdc++ -mwindows -Wl,--allow-multiple-definition"
    if re.search(r"^LDFLAGS\s*\+=", text, re.MULTILINE):
        text = re.sub(r"^LDFLAGS\s*\+=.*$", f"LDFLAGS += {static_ldflags}", text, flags=re.MULTILINE)
    else:
        text += f"\nLDFLAGS += {static_ldflags}\n"

    config_mk.write_text(text, encoding="utf-8")


def verify_dll_dependencies(exe_path: Path) -> list:
    res = run_msys(
        f"objdump -p '{to_msys_path(exe_path)}' | grep 'DLL Name:'",
        cwd=exe_path.parent,
        capture=True,
    )
    dlls = []
    non_system = []
    for line in res.stdout.splitlines():
        m = re.search(r"DLL Name:\s*(\S+)", line)
        if m:
            dll = m.group(1)
            dlls.append(dll)
            low = dll.lower()
            if low not in WINDOWS_SYSTEM_DLLS and not low.startswith("api-ms-win-"):
                non_system.append(dll)
    print(f"  Imported DLLs ({len(dlls)}): {', '.join(sorted(set(dlls)))}")
    if non_system:
        raise RuntimeError(f"Non-system DLL dependencies found in {exe_path.name}: {non_system}")
    print("  [OK] 100% static! Only native Windows system DLLs are imported.")
    return dlls


