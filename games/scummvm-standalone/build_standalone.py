def package_distribution(profile: dict, built_exe: Path, dist_root: Path) -> Path:
    dist_dir = dist_root / profile["output_folder"]
    dist_dir.mkdir(parents=True, exist_ok=True)

    target_exe = dist_dir / profile["executable_name"]
    run_msys(
        f"strip '{to_msys_path(built_exe)}' -o '{to_msys_path(target_exe)}'",
        cwd=built_exe.parent,
    )

    verify_dll_dependencies(target_exe)

    # Copy required GPLv3+ and third-party license files
    for src_name, dst_name in [
        ("COPYING", "COPYING.txt"),
        ("COPYRIGHT", "COPYRIGHT.txt"),
        ("AUTHORS", "AUTHORS.txt"),
    ]:
        src = REPO_ROOT / src_name
        if src.exists():
            shutil.copy2(src, dist_dir / dst_name)

    licenses_src = REPO_ROOT / "LICENSES"
    licenses_dst = dist_dir / "LICENSES"
    if licenses_src.exists():
        if licenses_dst.exists():
            shutil.rmtree(licenses_dst)
        shutil.copytree(licenses_src, licenses_dst)

    write_readme(profile, dist_dir)

    # Notify Windows Explorer to refresh cached executable icons immediately
    try:
        import ctypes
        SHCNE_UPDATEITEM = 0x00002000
        SHCNE_ASSOCCHANGED = 0x08000000
        SHCNF_PATHW = 0x0005
        SHCNF_IDLIST = 0x0000
        shell32 = ctypes.windll.shell32
        shell32.SHChangeNotify(SHCNE_UPDATEITEM, SHCNF_PATHW, str(target_exe), None)
        shell32.SHChangeNotify(SHCNE_ASSOCCHANGED, SHCNF_IDLIST, None, None)
    except Exception:
        pass

    size_mb = target_exe.stat().st_size / (1024 * 1024)
    print(f"[DONE] Packaged '{profile['display_name']}' -> {target_exe} ({size_mb:.2f} MB)")
    return target_exe


def build_game(profile_path: Path, build_root: Path, dist_root: Path, jobs: int, clean: bool, skip_configure: bool) -> Path:
    profile = json.loads(profile_path.read_text(encoding="utf-8"))
    app_id = profile["app_id"]
    engine = profile["engine"]

    print(f"\n============================================================")
    print(f"Building standalone: {profile['display_name']} (engine={engine})")
    print(f"============================================================")

    build_dir = build_root / app_id
    if clean and build_dir.exists():
        shutil.rmtree(build_dir)
    build_dir.mkdir(parents=True, exist_ok=True)

    generate_standalone_config_header(profile, build_dir)
    generate_standalone_rc(profile, build_dir)

    config_mk = build_dir / "config.mk"
    if not skip_configure or not config_mk.exists():
        configure_script = to_msys_path(REPO_ROOT / "configure")
        static_cxxflags = (
            "-O2 -fno-lto -DSCUMMVM_STANDALONE "
            "-DCURL_STATICLIB -DNGHTTP2_STATICLIB -DNGTCP2_STATICLIB "
            "-DNGHTTP3_STATICLIB -DFRIBIDI_LIB_STATIC"
        )
        cfg_flags = [
            "--backend=sdl",
            "--disable-all-engines",
            f"--enable-engine={engine}",
            "--disable-detection-full",
            "--disable-debug",
            "--enable-release",
            "--disable-cloud",
            "--disable-tts",
            "--disable-updates",
            "--disable-discord",
            "--disable-sdlnet",
        ] + profile.get("extra_configure_flags", [])

        run_msys(
            f"CXXFLAGS='{static_cxxflags}' '{configure_script}' {' '.join(cfg_flags)}",
            cwd=build_dir,
        )
        patch_config_mk_for_static_standalone(build_dir)

    # Compile custom standalone Windows resource object
    src_msys = to_msys_path(REPO_ROOT)
    run_msys(
        f"windres -DHAVE_CONFIG_H "
        f"-I. -I'{src_msys}' -I'{src_msys}/engines' "
        f"dists/standalone.rc -o dists/standalone.o",
        cwd=build_dir,
    )

    # Compile and link the standalone binary
    run_msys(f"make -j{jobs}", cwd=build_dir)

    built_exe = build_dir / "scummvm.exe"
    if not built_exe.exists():
        raise RuntimeError(f"Expected built executable not found: {built_exe}")

    return package_distribution(profile, built_exe, dist_root)


def main() -> int:
    parser = argparse.ArgumentParser(description="Build standalone Windows x64 executables from ScummVM-BR.")
    parser.add_argument("profiles", nargs="*", help="Path(s) to game profile JSON files.")
    parser.add_argument("--all", action="store_true", help="Build all game profiles in tools/standalone/games/.")
    parser.add_argument("--clean", action="store_true", help="Clean build directory before building.")
    parser.add_argument("--skip-configure", action="store_true", help="Skip ./configure if config.mk already exists.")
    parser.add_argument("--jobs", "-j", type=int, default=os.cpu_count() or 4, help="Parallel make jobs.")
    parser.add_argument("--build-root", type=Path, default=DEFAULT_BUILD_ROOT, help="Out-of-tree build root.")
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_DIST_ROOT, help="Output distribution directory.")
    args = parser.parse_args()

    profile_paths = []
    if args.all:
        profile_paths = sorted(GAMES_DIR.glob("*.json"))
    else:
        profile_paths = [Path(p) for p in args.profiles]

    if not profile_paths:
        parser.error("Provide one or more profile JSON files, or use --all.")

    built = []
    for p in profile_paths:
        exe = build_game(p, args.build_root, args.output_dir, args.jobs, args.clean, args.skip_configure)
        built.append(exe)

    print("\nAll standalone builds succeeded:")
    for exe in built:
        print(f"  - {exe}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
