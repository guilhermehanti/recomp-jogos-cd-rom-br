#!/usr/bin/env python3
"""
ScummVM-BR Standalone Builder

Generic, reusable build tool that compiles an independent, portable Windows x64
standalone executable for any ScummVM-supported game defined by a JSON profile.

Each standalone executable:
  - Compiles only the required ScummVM engine and its minimal dependencies.
  - Statically links all third-party libraries (zero MinGW/MSYS2 DLLs required).
  - Embeds ScummVM GUI themes, shaders, and translations (without launcher icons).
  - Never includes or distributes any original game files.
  - Prompts for and validates the user's original ISO on first run, then reads
    directly from the ISO with zero extraction or virtual drive mounting.
  - Preserves the full ScummVM settings menu (OpenGL, shaders + shader downloads,
    scalers, aspect ratio, fullscreen, filtering, vsync, audio, keymaps, etc.).
  - Packages required GPLv3+ license files alongside the standalone executable.
"""

