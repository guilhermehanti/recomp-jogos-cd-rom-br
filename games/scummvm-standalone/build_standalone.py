    icon_rel = profile.get("icon", "").strip()
    if icon_rel:
        icon_candidate = Path(icon_rel)
        if not icon_candidate.is_absolute():
            icon_candidate = REPO_ROOT / icon_candidate
        if not icon_candidate.exists():
            raise FileNotFoundError(f"Configured icon not found: {icon_candidate}")
